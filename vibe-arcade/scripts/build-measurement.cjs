"use strict";
const fs=require('node:fs'),path=require('node:path');
function build(){const root=path.resolve(__dirname,'..'),body=['measurement/contract.js','measurement/browser.js'].map(p=>fs.readFileSync(path.join(root,p),'utf8')).join('\n');for(const file of ['arcade3/telemetry.js','analytics.js'])fs.writeFileSync(path.join(root,file),'/* Generated by scripts/build-measurement.cjs. Edit measurement sources. */\n'+body);}
if(require.main===module)build();module.exports={build};
